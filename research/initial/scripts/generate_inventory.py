"""Regenerate finite combinatorial invoice for the two-chain exact-DFT witness.

This checks the identities linking the native P104 helper/paid profile to the
published 9|9 caller. It does not establish universal operator correctness.
"""
from pathlib import Path
from hashlib import sha256
import json

ROOT = Path(__file__).resolve().parents[1]
HELPER = {1:14, 2:8, 3:4, 4:107, 5:14, 6:2, 7:9, 8:19, 9:385}
PAID = {1:2216, 2:456, 3:496, 4:98, 5:165, 6:8, 7:9, 8:1}
EXPECTED_TARGET = {1:712,2:288,3:144,4:3852,5:504,6:72,7:324,8:684,9:14276,
                   17:416,25:416,33:416,41:416,49:416,57:416,65:416,73:416,145:208}
EXPECTED_PAID = {1:80400,2:16416,3:17856,4:3528,5:5940,6:288,7:324,8:452,
                 16:416,24:416,32:416,40:416,48:416,56:416,64:416}

def kronecker(a,b): return int(a==b)

def target_formula(r):
    return 2*(18*HELPER.get(r,0)+104*(kronecker(r,1)+kronecker(r,145)
            +2*sum(kronecker(r,8*j+1) for j in range(1,10))))

def paid_formula(r):
    return 2*(18*PAID.get(r,0)+104*(3*kronecker(r,1)
            +2*sum(kronecker(r,8*j) for j in range(1,9))))

T = {r:target_formula(r) for r in range(146) if target_formula(r)}
P = {r:paid_formula(r) for r in range(146) if paid_formula(r)}
assert T == EXPECTED_TARGET, (T,EXPECTED_TARGET)
assert P == EXPECTED_PAID, (P,EXPECTED_PAID)
assert (sum(T.values()),sum(P.values())) == (24392,128116)
assert (sum(r*n for r,n in T.items()),sum(r*n for r,n in P.items())) == (336224,334704)
assert max(P)==64 and max(T)==145


def matchdef(name, profile):
    lines = [f"/-- Literal normalized-gauge physical histogram `{name}`. -/",f"def {name} : ℕ → ℕ"]
    for r,c in sorted(profile.items()): lines.append(f"  | {r} => {c}")
    lines.append("  | _ => 0")
    return '\n'.join(lines)

prefix = '''import Mathlib

/-!
# Exact finite invoice for the paired two-chain DFT construction

The tables below are the result of *paid* source calls and independent
productive outputs, including two complex copies. These are arithmetic
certificates of the asserted histogram, not proof that the underlying
operator word realizes the required array maps.

Generated by `scripts/generate_inventory.py`.
-/

set_option maxRecDepth 8192
set_option maxHeartbeats 2000000

namespace FFTChainDFT
namespace Inventory

'''
body = [matchdef('helperPerNative', HELPER),matchdef('paidPerNative', PAID),
        matchdef('targetCount', T),matchdef('paidCount', P)]
body.append('''
/-- Kronecker indicator, over natural multiplicities. -/
def indicator (r s : ℕ) : ℕ := if r = s then 1 else 0

/-- Multiplicity reconstructed from 18 native sites, main endpoints and 2 copies. -/
def targetFromFormula (r : ℕ) : ℕ :=
  2 * (18 * helperPerNative r +
    104 * (indicator r 1 + indicator r 145 +
      2 * (Finset.Icc 1 9).sum (fun j => indicator r (8 * j + 1))))

/-- Multiplicity reconstructed from native sites, three thin queries, 16 whole idles. -/
def paidFromFormula (r : ℕ) : ℕ :=
  2 * (18 * paidPerNative r +
    104 * (3 * indicator r 1 +
      2 * (Finset.Icc 1 8).sum (fun j => indicator r (8 * j))))

/-- The literal histogram is exactly the independently reconstructed formula
    at all relevant ranks `0 ≤ r ≤ 145`. -/
theorem complete_target_formula :
    (Finset.range 146).sum (fun r =>
       if targetCount r = targetFromFormula r then (0 : ℕ) else 1) = 0 := by
  decide

theorem complete_paid_formula :
    (Finset.range 146).sum (fun r =>
       if paidCount r = paidFromFormula r then (0 : ℕ) else 1) = 0 := by
  decide

/-- Both physical multiplicities include two independent complex-array copies. -/
theorem productive_field_count :
    (Finset.range 146).sum targetCount = 24392 := by decide

theorem paid_block_count :
    (Finset.range 146).sum paidCount = 128116 := by decide

/-- Rank masses, not just total numbers of calls, are charged. -/
theorem productive_rank_mass :
    (Finset.range 146).sum (fun r => r * targetCount r) = 336224 := by decide

theorem paid_rank_mass :
    (Finset.range 146).sum (fun r => r * paidCount r) = 334704 := by decide

/-- Exact nonzero rank-mass surplus: this alone is NOT a power saving. -/
theorem surplus_rank_mass :
    (Finset.range 146).sum (fun r => r * targetCount r) -
      (Finset.range 146).sum (fun r => r * paidCount r) = 1520 := by decide

/-- The lists contain no nonzero paid ranks above 64, up to rank 145. -/
theorem paid_rank_cap_checked :
    (Finset.Icc 65 145).sum paidCount = 0 := by decide

end Inventory
end FFTChainDFT
''')
content = prefix + '\n\n'.join(body) + '\n'
path = ROOT/'FFTChainDFT'/'Inventory.lean'
path.write_text(content,encoding='utf-8')
receipt = {'T':T,'P':P,'n_targets':sum(T.values()),'n_paid':sum(P.values()),
           'rank_targets':sum(r*n for r,n in T.items()),
           'rank_paid':sum(r*n for r,n in P.items()),
           'source':'User research PDF dated 2026-11-08, sections 2,5,6',
           'lean_inventory_sha256':sha256(content.encode()).hexdigest()}
(ROOT/'inventory_receipt.json').write_text(json.dumps(receipt,indent=2,ensure_ascii=False)+'\n')
print(f'PASS_INVENTORY generated={path.name} sha256={receipt["lean_inventory_sha256"]}')
