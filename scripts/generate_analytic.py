"""Generate rational certificates replayed by Lean's kernel, not trusted Python.

Log endpoints are proposed with a rational atanh series. Lean independently
checks them via exponential series bounds inherited from Sussman/Kartal.
"""
from fractions import Fraction as F
from pathlib import Path
from math import factorial
import json

ROOT = Path(__file__).resolve().parents[1]
INV = json.loads((ROOT / 'inventory_receipt.json').read_text())
T = {int(r): n for r, n in INV['T'].items()}
P = {int(r): n for r, n in INV['P'].items()}
C = F(420453, 125000000)
G = 10**12
H = 10**14

def log_reduced(x):
    z = (x-1)/(x+1)
    return sum((2*z**(2*j+1)/(2*j+1) for j in range(22)), F(0))

def log_estimate(r):
    k = r.bit_length()-1
    return k*log_reduced(F(2)) + log_reduced(F(r, 2**k))

def es(x, n):
    return sum((x**i/factorial(i) for i in range(n)), F(0))

def eu(x, n):
    return es(x, n)+x**n*(n+1)/(factorial(n)*n)

def floor(x, grid):
    return F((x.numerator*grid)//x.denominator, grid)

def ceil(x, grid):
    return -floor(-x, grid)

def lean(q):
    q = F(q)
    if q.denominator == 1:
        return f'({q.numerator} : ℝ)'
    return f'(({q.numerator} : ℝ) / {q.denominator})'

logs = {}
powers = {}
